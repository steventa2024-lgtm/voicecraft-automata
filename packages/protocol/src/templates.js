for (const row of SPECS) {
  if ({ ...CATALOG_DEFAULTS, ...SHOWCASE_DEFAULTS }[row[0]])
    [row[4], row[5]] = { ...CATALOG_DEFAULTS, ...SHOWCASE_DEFAULTS }[row[0]];
}

function specById(id) {
  return SPECS.find((row) => row[0] === id) || null;
}

function publicTemplate(row, sample) {
  const [
    id,
    name,
    category,
    description,
    width,
    depth,
    floors,
    material,
    complexity,
    tags,
    warnings,
  ] = row;
  return {
    id,
    name,
    category,
    description,
    generatorId: id,
    generatorVersion: GENERATOR_VERSION,
    defaults: { width, depth, floors, material, accent: "stone_bricks" },
    ranges: {
      width: [Math.max(7, width - 2), width + 4],
      depth: [Math.max(3, depth - 2), depth + 4],
      floors: floors > 1 ? [1, floors] : [1, 1],
    },
    complexity,
    tags,
    warnings,
    minecraft: "1.21.1",
    permissions: "The placing account must be allowed to build in the target world.",
    estimatedBlocks: sample.count,
    bounds: sample.bounds,
    supports: { rotate: true, mirror: true, floors: floors > 1, resize: true },
  };
}

export function generateTemplate(id, options = {}) {
  const row = specById(id);
  const builder = SHOWCASE_BUILDERS[id] || CATALOG_BUILDERS[id];
  if (!row || !builder) {
    const error = new Error(`Unknown structure template: ${id}`);
    error.code = "unknown_template";
    throw error;
  }
  const [, , , , defaultWidth, defaultDepth, defaultFloors, defaultMaterial] = row;
  const width = clamp(options.width, Math.max(7, defaultWidth - 2), defaultWidth + 4, defaultWidth);
  const depth = clamp(options.depth, Math.max(3, defaultDepth - 2), defaultDepth + 4, defaultDepth);
  const floors = clamp(options.floors, 1, defaultFloors > 1 ? defaultFloors : 1, defaultFloors);
  const material =
    typeof options.material === "string" && /^[a-z0-9_]+$/.test(options.material)
      ? options.material
      : defaultMaterial;
  let blocks = dedupe(
    builder({ w: width, d: depth, floors, material, accent: options.accent || "stone_bricks" }),
  );
  const mirror = options.mirror === "x" || options.mirror === "z" ? options.mirror : null;
  if (mirror) blocks = dedupe(mirrorBlocks(blocks, mirror));
  const rotation = clamp(options.rotation, 0, 3, 0);
  if (rotation) blocks = dedupe(rotateBlocks(blocks, rotation));
  const placement = options.placement ?? "ground";
  if (!["ground", "floating"].includes(placement)) {
    throw new Error(
      "Water-surface placement is not supported. Choose ground or a vertical offset.",
    );
  }
  const elevation = placement === "floating" ? clamp(options.elevation, 1, 16, 4) : 0;
  if (elevation) blocks = blocks.map((block) => ({ ...block, y: block.y + elevation }));
  const bounds = boundsOf(blocks);
  return {
    templateId: id,
    generatorVersion: GENERATOR_VERSION,
    blocks,
    count: blocks.length,
    bounds,
    fingerprint: planFingerprint(blocks),
    warnings: [
      ...row[10],
      ...(elevation
        ? [`Raised ${elevation} blocks from the normal placement origin. Supports are not added.`]
        : []),
    ],
    settings: {
      width,
      depth,
      floors,
      material,
      accent: options.accent || "stone_bricks",
      rotation,
      mirror,
      placement,
      elevation,
    },
  };
}

let catalogCache = null;

export function listTemplates() {
  if (!catalogCache) {
    catalogCache = SPECS.map((row) => publicTemplate(row, generateTemplate(row[0])));
  }
  return catalogCache;
}

export function templateById(id) {
  return listTemplates().find((template) => template.id === id) || null;
}

/** Compatibility API, now using the same state-aware geometry as both applications. */
export function isometricPreview(blocks, width = 280, height = 200) {
  const scene = voxelScene(blocks, width, height, 2);
  return {
    width,
    height,
    faces: scene.faces,
    cells: scene.faces.map((f) => ({
      x: f.points.reduce((a, p) => a + p.x, 0) / 4,
      y: f.points.reduce((a, p) => a + p.y, 0) / 4,
      color: f.color,
      depth: f.depth,
    })),
  };
}
